
List = [1,56,23,5,12,9,7,99]

#=========================================================
# sort(): Updates the list in regular order
List.sort()
print(List)

#=========================================================
# reverse(): Updates the list in reverse order of numbering
List.reverse()
print(List)

#============================================================
# append(8): Adds the number at the end of the list
List.append(8)
print(List) 

#============================================================
# insert(3,8): This will add 8 at index 3
List.insert(3,8)
print(List)

#==============================================================
# pop(2): It will delete element at index 2, and return its value
List.pop(2)
print(List)

